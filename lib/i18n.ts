export function normalizeLocale(value: unknown): Locale {
  return typeof value === "string" && value.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function resolveInitialLocale(stored: unknown, browserLanguage: unknown): Locale {
  if (stored === "en" || stored === "ja") return stored;
  return normalizeLocale(browserLanguage);
}

export function translate(locale: Locale, key: TranslationKey | string, values: Record<string, string | number> = {}): string {
  const source = (locale === "ja" ? japanese[key as TranslationKey] : undefined) ?? english[key as TranslationKey] ?? key;
  return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), source);
}

export function domainLabel(locale: Locale, domain: string, fallback = domain): string {
  const key = `domain.${domain}`;
  const value = translate(locale, key);
  return value === key ? fallback : value;
}

export function categoryLabel(locale: Locale, category: string): string {
  const key = `category.${category}`;
  const value = translate(locale, key);
  return value === key ? category : value;
}

export function tasteSignalLabel(locale: Locale, signal: string): string {
  const key = `signal.${signal.toLowerCase()}`;
  const value = translate(locale, key);
  return value === key ? signal : value;
}

export function statusToken(mode: string): string {
  return ["LIVE", "DEMO", "FALLBACK", "NEEDS_INPUT"].includes(mode) ? mode : mode;
}

export function statusExplanation(locale: Locale, mode: string): string {
  const key = mode === "LIVE" ? "status.liveExplanation" : mode === "DEMO" ? "status.demoExplanation" : mode === "NEEDS_INPUT" ? "status.needsInputExplanation" : "status.fallbackExplanation";
  return translate(locale, key);
}

